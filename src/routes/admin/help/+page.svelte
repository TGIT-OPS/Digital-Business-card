<div class="card">
	<h2>Cards</h2>
	<p>Create a card from Cards → New card. Build holds the person, photo and videos. Customize offers the TGIT palettes only. Set-up holds the short URL, QR template, labels, and the two sharing switches. The short URL can be changed until the first save, then it stays put.</p>
	<p style="margin-top:10px">Duplicate makes another card you can rename. Labels show on the card list. The company filter narrows that list.</p>
	<h2 style="margin-top:18px">Public card</h2>
	<p>The public page plays the front, flips to the back, and repeats. A tap flips it immediately. People who prefer reduced motion see the still poster and no automatic flip. Exchange Contacts saves a lead. Save Contact downloads a vCard.</p>
	<h2 style="margin-top:18px">Contacts and analytics</h2>
	<p>Contact Manager lists leads, notes and a CSV download. Analytics shows views, saves and clicks per day, plus country and city when location tracking is on.</p>
	<h2 style="margin-top:18px">Files</h2>
	<p>Asset Library lists everything in the media bucket. Upload, copy the public URL, or delete. Header videos should stay under 8 MB.</p>
